CREATE TABLE career (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(32)  NOT NULL,
    name          VARCHAR(160) NOT NULL,
    institution   VARCHAR(160) NOT NULL,
    total_credits INTEGER      NOT NULL,
    CONSTRAINT uq_career_code UNIQUE (code)
);

CREATE TABLE course (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    career_id      BIGINT       NOT NULL,
    code           VARCHAR(32)  NOT NULL,
    name           VARCHAR(160) NOT NULL,
    credits        INTEGER      NOT NULL,
    suggested_term INTEGER      NOT NULL,
    CONSTRAINT fk_course_career FOREIGN KEY (career_id) REFERENCES career (id) ON DELETE CASCADE,
    CONSTRAINT uq_course_code UNIQUE (career_id, code)
);

CREATE TABLE prerequisite (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id          BIGINT NOT NULL,
    required_course_id BIGINT NOT NULL,
    CONSTRAINT fk_prerequisite_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_prerequisite_required FOREIGN KEY (required_course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT uq_prerequisite UNIQUE (course_id, required_course_id),
    CONSTRAINT ck_prerequisite_not_self CHECK (course_id <> required_course_id)
);

CREATE TABLE plan_run (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    career_id            BIGINT       NOT NULL,
    created_at           TIMESTAMP    NOT NULL,
    approved_count       INTEGER      NOT NULL,
    failed_count         INTEGER      NOT NULL,
    failed_codes         VARCHAR(4000),
    max_credits_per_term INTEGER      NOT NULL,
    total_terms          INTEGER      NOT NULL,
    delay_terms          INTEGER      NOT NULL,
    CONSTRAINT fk_plan_run_career FOREIGN KEY (career_id) REFERENCES career (id) ON DELETE CASCADE
);

CREATE INDEX idx_course_career ON course (career_id);
CREATE INDEX idx_prerequisite_course ON prerequisite (course_id);
CREATE INDEX idx_plan_run_career ON plan_run (career_id, created_at);
